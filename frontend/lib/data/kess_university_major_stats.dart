class UniversityMajorStat {
  const UniversityMajorStat({
    required this.largeCategory,
    required this.middleCategory,
    required this.smallCategory,
    required this.admissionQuotaRegular,
    required this.admissionQuotaExtra,
    required this.recruitmentRegular,
    required this.recruitmentExtra,
    required this.applicantsTotal,
    required this.entrantsTotal,
  });

  final String largeCategory;
  final String middleCategory;
  final String smallCategory;
  final int admissionQuotaRegular;
  final int admissionQuotaExtra;
  final int recruitmentRegular;
  final int recruitmentExtra;
  final int applicantsTotal;
  final int entrantsTotal;

  bool get isDetail =>
      !largeCategory.contains('총계') && !smallCategory.startsWith('[');

  int get admissionQuotaTotal => admissionQuotaRegular + admissionQuotaExtra;
  int get recruitmentTotal => recruitmentRegular + recruitmentExtra;

  double get fillRate {
    final quota = admissionQuotaRegular;
    if (quota == 0) {
      return 0;
    }
    return entrantsTotal / quota * 100;
  }

  bool matches(String query) {
    final trimmed = query.trim().toLowerCase();
    if (trimmed.isEmpty) {
      return true;
    }
    return largeCategory.toLowerCase().contains(trimmed) ||
        middleCategory.toLowerCase().contains(trimmed) ||
        smallCategory.toLowerCase().contains(trimmed);
  }
}

