-- ETMS enterprise gap-closure module.
-- PostgreSQL 11 compatible. This module intentionally contains tables only;
-- request-context security functions, RLS policies, indexes, and triggers belong in module 11.

-- ---------------------------------------------------------------------------
-- Secure identity, organization governance, access review, SOD, legal hold,
-- data-subject operations, and audit integrity support.
-- ---------------------------------------------------------------------------

-- These short-lived, transaction-bound rows are security control-plane state,
-- not ordinary tenant-owned business records. Module 11 owns the SECURITY
-- DEFINER functions that populate, validate, and clear them.
CREATE TABLE IF NOT EXISTS etms.request_contexts (
    backend_pid integer NOT NULL,
    transaction_id bigint NOT NULL,
    bound_tenant_id uuid NOT NULL REFERENCES etms.tenants(id),
    bound_user_id uuid NOT NULL REFERENCES etms.users(id),
    bound_membership_id uuid NOT NULL REFERENCES etms.tenant_memberships(id),
    bound_session_id uuid NOT NULL REFERENCES etms.auth_sessions(id),
    request_id uuid NOT NULL,
    assurance_level smallint NOT NULL DEFAULT 1,
    source_ip inet,
    user_agent_hash char(64),
    established_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    expires_at timestamptz NOT NULL,
    context_digest char(64) NOT NULL,
    PRIMARY KEY (backend_pid, transaction_id),
    UNIQUE (request_id),
    CONSTRAINT ck_request_context_backend CHECK (backend_pid > 0 AND transaction_id > 0),
    CONSTRAINT ck_request_context_assurance CHECK (assurance_level BETWEEN 0 AND 4),
    CONSTRAINT ck_request_context_expiry CHECK (expires_at > established_at)
);

